// @vitest-environment jsdom
import { beforeEach, expect, it, vi } from 'vitest'
import { mount, flushPromises } from '@vue/test-utils'
const m = vi.hoisted(() => ({ preview: vi.fn(), run: vi.fn(), overview: vi.fn() }))
vi.mock('@/api/closing', () => ({ closingApi: { deferredTax504Preview: m.preview, deferredTax504Run: m.run } }))
vi.mock('@/api/dimensions', () => ({ dimensionsApi: { overview: m.overview } }))
vi.mock('vue-i18n', () => ({ useI18n: () => ({ t: (key: string) => key }) }))
vi.mock('@/composables/useFormat', () => ({ formatMoney: String, formatDate: String }))
import DeferredTax504Panel from '../DeferredTax504Panel.vue'
const method = { enabled: true, version: '504-deferred-own-v1', first_adoption: false, reference: 'SYN-METHOD', faithful_image_reason: 'Synthetic faithful image', standard_departure_reason: 'Synthetic departure', presentation_reason: 'Synthetic presentation' }
const title = { reference: 'SYN-TITLE', evidence: 'Synthetic difference', kind: 'taxable', difference: '1000.00', rate_percent: '21.00', rate_basis: 'Synthetic enacted rate', temporary_confirmed: true, dimensions: { 1: 11 } }
beforeEach(() => {
  vi.clearAllMocks()
  m.overview.mockResolvedValue({ types: [{ id: 1, name: 'Activity', system_key: 'activity', is_active: true }], values: [{ id: 11, type_id: 1, name: 'Economic', is_active: true }] })
  m.preview.mockImplementation((_id, body) => Promise.resolve({ source_hash: 'synthetic-source-hash', accounting_framework: 'cz_504', as_of: '2097-12-31', row_version: 4, enabled: Boolean(body), decision: null, assessment: body ? { enabled: true, closing: { liability_cents: 21000, asset_cents: 0, unrecognized_asset_cents: 0 } } : { enabled: false }, movements: { opening: [], closing: [{ account_code: '592', side: 'debit', amount: 210 }] } }))
  m.run.mockResolvedValue({ entry_ids: [8] })
})
it('defaults off and validates before structured read-only preview', async () => {
  const w = mount(DeferredTax504Panel, { props: { periodId: 1, rowVersion: 4, canWrite: true } })
  await flushPromises()
  expect((w.get('[data-test=deferred-enabled]').element as HTMLInputElement).checked).toBe(false)
  await w.get('[data-test=deferred-enabled]').setValue(true)
  const validity = vi.spyOn(w.get('form').element, 'reportValidity').mockReturnValue(false)
  await w.get('form').trigger('submit')
  expect(validity).toHaveBeenCalled()
  expect(m.preview).toHaveBeenCalledTimes(1)
  expect(m.run).not.toHaveBeenCalled()
})
it('requires reviewed preview and preserves exact decision strings', async () => {
  m.preview.mockResolvedValueOnce({ source_hash: 'synthetic-source-hash', accounting_framework: 'cz_504', as_of: '2097-12-31', row_version: 4, enabled: true, decision: { method, titles: [title] }, assessment: { enabled: true }, movements: { opening: [], closing: [] } })
  const w = mount(DeferredTax504Panel, { props: { periodId: 1, rowVersion: 4, canWrite: true } })
  await flushPromises()
  expect(w.find('[data-test=deferred-post]').exists()).toBe(false)
  await w.get('form').trigger('submit')
  await flushPromises()
  expect(m.preview).toHaveBeenLastCalledWith(1, expect.objectContaining({ method, titles: [title] }))
  expect(w.get('[data-test=deferred-totals]').text()).toContain('210')
  await w.get('[data-test=deferred-post]').trigger('click')
  await flushPromises()
  expect(m.run).toHaveBeenCalledWith(1, 4, expect.objectContaining({ method, titles: [title], source_hash: 'synthetic-source-hash' }))
  expect(w.emitted('updated')).toHaveLength(1)
})
it('rejects fractional cents and invalidates confirmed preview after an edit', async () => {
  m.preview.mockResolvedValueOnce({ source_hash: 'synthetic-source-hash', accounting_framework: 'cz_504', as_of: '2097-12-31', row_version: 4, enabled: true, decision: { method, titles: [title] }, assessment: { enabled: true }, movements: { opening: [], closing: [] } })
  const w = mount(DeferredTax504Panel, { props: { periodId: 1, rowVersion: 4, canWrite: true } })
  await flushPromises()
  await w.get('form').trigger('submit')
  await flushPromises()
  expect(w.find('[data-test=deferred-post]').exists()).toBe(true)
  await w.get('[data-test=deferred-difference]').setValue('0.005')
  expect(w.find('[data-test=deferred-post]').exists()).toBe(false)
  await w.get('form').trigger('submit')
  expect(m.preview).toHaveBeenCalledTimes(2)
  expect(m.run).not.toHaveBeenCalled()
})

it('does not confirm a preview without its source receipt', async () => {
  m.preview.mockResolvedValueOnce({ source_hash: 'old', accounting_framework: 'cz_504', as_of: '2097-12-31', row_version: 4, enabled: true, decision: { method, titles: [title] }, assessment: { enabled: true }, movements: { opening: [], closing: [] } })
  const w = mount(DeferredTax504Panel, { props: { periodId: 1, rowVersion: 4, canWrite: true } })
  await flushPromises()
  m.preview.mockResolvedValueOnce({ accounting_framework: 'cz_504', row_version: 4 })
  await w.get('form').trigger('submit')
  await flushPromises()
  expect(w.find('[data-test=deferred-post]').exists()).toBe(false)
  expect(m.run).not.toHaveBeenCalled()
})
it('invalidates the receipt on version change and requires a fresh preview', async () => {
  m.preview.mockResolvedValueOnce({ source_hash: 'initial', accounting_framework: 'cz_504', as_of: '2097-12-31', row_version: 4, enabled: true, decision: { method, titles: [title] }, assessment: { enabled: true }, movements: { opening: [], closing: [] } })
  const w = mount(DeferredTax504Panel, { props: { periodId: 1, rowVersion: 4, canWrite: true } })
  await flushPromises()
  await w.get('form').trigger('submit')
  await flushPromises()
  await w.setProps({ rowVersion: 5 })
  expect(w.find('[data-test=deferred-post]').exists()).toBe(false)
  m.preview.mockResolvedValueOnce({ source_hash: 'fresh', accounting_framework: 'cz_504', row_version: 5, assessment: {}, movements: { opening: [], closing: [] } })
  await w.get('form').trigger('submit')
  await flushPromises()
  await w.get('[data-test=deferred-post]').trigger('click')
  await flushPromises()
  expect(m.run).toHaveBeenCalledWith(1, 5, expect.objectContaining({ source_hash: 'fresh' }))
})

it('explains why a changed assessment must be reviewed again', async () => {
  m.preview.mockResolvedValueOnce({ source_hash: 'changed', accounting_framework: 'cz_504', as_of: '2097-12-31', row_version: 4, enabled: true, assessment_current: false, decision: { method, titles: [title] }, assessment: { enabled: true }, movements: { opening: [], closing: [] } })
  const w = mount(DeferredTax504Panel, { props: { periodId: 1, rowVersion: 4, canWrite: true } })
  await flushPromises()
  expect(w.get('[data-test=deferred-stale]').text()).toBe('accounting.deferred504.stale')
  expect(w.find('[data-test=deferred-post]').exists()).toBe(false)
})
