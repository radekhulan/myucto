-- EET 2.0: platební události, evidované tržby a pokusy o odeslání.
--
-- payment_events = provozní a fiskální obálka jedné skutečné platby (identita,
-- idempotence, kontext, oddělené stavy platebního příkazu, banky a účetnictví).
-- Účetní úhrada dál žije v invoice_payments; vazbu drží payment_event_allocations.
-- eet_records = neměnný snapshot tržby (EIČ, jednotka, zařízení, pořadové číslo,
-- čas, částka, prostředí) a stav odesílání (outbox s lease). eet_attempts = každý
-- pokus o odeslání s vlastním UUID zprávy.
--
-- Vazby na zdrojové doklady nejsou kaskádové: historii EET nesmí smazat smazání
-- dokladu ani úhrady (chrání InvoicePaymentService). Kaskádu má jen firma.

SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS payment_events (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    public_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    supplier_id INT UNSIGNED NOT NULL,
    idempotency_key VARCHAR(80) CHARACTER SET ascii COLLATE ascii_bin NULL,
    request_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    confirm_idempotency_key VARCHAR(80) CHARACTER SET ascii COLLATE ascii_bin NULL,
    confirm_request_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    kind ENUM('payment','refund','intent') NOT NULL,
    origin ENUM('invoice_payment','cash_document','quick_sale','payment_intent','correction','bank_reconciliation','api') NOT NULL,
    payment_method VARCHAR(30) NULL,
    channel ENUM('cash','card_terminal','qr_in_person','bank_transfer','card_online','cash_on_delivery','other') NULL,
    contact_context ENUM('in_person','on_premises','in_vehicle','remote','unknown') NOT NULL,
    business_purpose ENUM('sale','order_deposit','credit_topup','credit_draw','security_deposit','other') NOT NULL DEFAULT 'sale',
    amount DECIMAL(14,2) NOT NULL,
    currency CHAR(3) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'CZK',
    ordered_at DATETIME(6) NULL,
    received_at DATETIME(6) NULL,
    recorded_at DATETIME(6) NOT NULL,
    paid_on DATE NULL,
    payment_order_status ENUM('initiated','operator_confirmed','settled','failed','cancelled') NOT NULL,
    bank_verification_status ENUM('not_applicable','pending','verified') NOT NULL DEFAULT 'not_applicable',
    accounting_settlement_status ENUM('not_applicable','pending','settled') NOT NULL DEFAULT 'pending',
    invoice_id BIGINT UNSIGNED NULL,
    device_id BIGINT UNSIGNED NULL,
    unit_id BIGINT UNSIGNED NULL,
    eet_decision ENUM('required','voluntary','not_subject','unknown','unsupported','inactive') NOT NULL,
    eet_reason_code VARCHAR(60) NULL,
    policy_version VARCHAR(20) NULL,
    corrects_event_id BIGINT UNSIGNED NULL,
    note VARCHAR(255) NULL,
    created_by BIGINT UNSIGNED NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uq_payment_events_public (public_id),
    UNIQUE KEY uq_payment_events_idempotency (supplier_id, idempotency_key),
    UNIQUE KEY uq_payment_events_confirm_idempotency (supplier_id, confirm_idempotency_key),
    KEY ix_payment_events_recorded (supplier_id, recorded_at, id),
    KEY ix_payment_events_invoice (supplier_id, invoice_id),
    KEY ix_payment_events_corrects (supplier_id, corrects_event_id),
    CONSTRAINT fk_payment_events_supplier FOREIGN KEY (supplier_id) REFERENCES supplier(id) ON DELETE CASCADE,
    CONSTRAINT chk_payment_events_amount CHECK (amount <> 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS payment_event_allocations (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    supplier_id INT UNSIGNED NOT NULL,
    payment_event_id BIGINT UNSIGNED NOT NULL,
    invoice_id BIGINT UNSIGNED NULL,
    invoice_payment_id BIGINT UNSIGNED NULL,
    cash_document_id BIGINT UNSIGNED NULL,
    bank_transaction_id BIGINT UNSIGNED NULL,
    amount DECIMAL(14,2) NOT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uq_payment_event_alloc_invoice_payment (invoice_payment_id),
    UNIQUE KEY uq_payment_event_alloc_cash_document (cash_document_id, payment_event_id),
    KEY ix_payment_event_alloc_event (supplier_id, payment_event_id),
    KEY ix_payment_event_alloc_invoice (supplier_id, invoice_id),
    CONSTRAINT fk_payment_event_alloc_supplier FOREIGN KEY (supplier_id) REFERENCES supplier(id) ON DELETE CASCADE,
    CONSTRAINT fk_payment_event_alloc_event FOREIGN KEY (payment_event_id) REFERENCES payment_events(id) ON DELETE CASCADE,
    CONSTRAINT fk_payment_event_alloc_invoice_payment FOREIGN KEY (invoice_payment_id) REFERENCES invoice_payments(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS eet_records (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    public_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    supplier_id INT UNSIGNED NOT NULL,
    payment_event_id BIGINT UNSIGNED NULL,
    kind ENUM('sale','correction','diagnostic') NOT NULL,
    corrects_record_id BIGINT UNSIGNED NULL,
    correction_reason ENUM('refund','failed_payment','wrong_data','duplicate','other') NULL,
    environment ENUM('playground','production') NOT NULL,
    eic VARCHAR(12) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    delegating_eic VARCHAR(12) CHARACTER SET ascii COLLATE ascii_bin NULL,
    unit_id BIGINT UNSIGNED NOT NULL,
    unit_number INT UNSIGNED NOT NULL,
    device_id BIGINT UNSIGNED NOT NULL,
    device_code VARCHAR(20) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    sequence_number VARCHAR(25) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    sale_at DATETIME NOT NULL,
    sale_at_offset CHAR(6) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    total_amount DECIMAL(12,2) NOT NULL,
    credit_topup_amount DECIMAL(12,2) NULL,
    credit_draw_amount DECIMAL(12,2) NULL,
    policy_decision VARCHAR(20) NULL,
    policy_reason VARCHAR(60) NULL,
    policy_version VARCHAR(20) NULL,
    status ENUM('pending','sending','retry_wait','confirmed','confirmed_warning','action_required','verification_ok') NOT NULL DEFAULT 'pending',
    action_code VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NULL,
    deadline_at DATETIME NOT NULL,
    overdue TINYINT(1) NOT NULL DEFAULT 0,
    next_attempt_at DATETIME(6) NULL,
    lease_token CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    lease_until DATETIME(6) NULL,
    attempt_count INT UNSIGNED NOT NULL DEFAULT 0,
    pok VARCHAR(39) CHARACTER SET ascii COLLATE ascii_bin NULL,
    confirmed_at DATETIME(6) NULL,
    last_error_code INT NULL,
    last_error_message VARCHAR(500) NULL,
    warnings_json LONGTEXT NULL CHECK (warnings_json IS NULL OR JSON_VALID(warnings_json)),
    created_by BIGINT UNSIGNED NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uq_eet_records_public (public_id),
    UNIQUE KEY uq_eet_records_sequence (device_id, sequence_number),
    UNIQUE KEY uq_eet_records_event_kind (payment_event_id, kind),
    KEY ix_eet_records_sale (supplier_id, sale_at, id),
    KEY ix_eet_records_status_deadline (supplier_id, status, deadline_at, id),
    KEY ix_eet_records_status_sale (supplier_id, status, sale_at, id),
    KEY ix_eet_records_unit_sale (supplier_id, unit_id, sale_at, id),
    KEY ix_eet_records_device_sale (supplier_id, device_id, sale_at, id),
    KEY ix_eet_records_corrects (supplier_id, corrects_record_id),
    KEY ix_eet_records_confirmed (supplier_id, confirmed_at),
    KEY ix_eet_due (status, next_attempt_at, id),
    CONSTRAINT fk_eet_records_supplier FOREIGN KEY (supplier_id) REFERENCES supplier(id) ON DELETE CASCADE,
    CONSTRAINT fk_eet_records_event FOREIGN KEY (payment_event_id) REFERENCES payment_events(id) ON DELETE CASCADE,
    CONSTRAINT chk_eet_records_amount CHECK (total_amount > -100000000 AND total_amount < 100000000)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS eet_attempts (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    supplier_id INT UNSIGNED NOT NULL,
    record_id BIGINT UNSIGNED NOT NULL,
    attempt_no INT UNSIGNED NOT NULL,
    uuid_zpravy CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    sent_at DATETIME(6) NOT NULL,
    first_attempt TINYINT(1) NOT NULL,
    verification TINYINT(1) NOT NULL DEFAULT 0,
    certificate_id BIGINT UNSIGNED NULL,
    outcome VARCHAR(30) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    http_status SMALLINT NULL,
    error_code INT NULL,
    error_message VARCHAR(500) NULL,
    pok VARCHAR(39) CHARACTER SET ascii COLLATE ascii_bin NULL,
    test_flag TINYINT(1) NULL,
    signature_verified TINYINT(1) NOT NULL DEFAULT 0,
    duration_ms INT UNSIGNED NULL,
    request_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    request_xml MEDIUMTEXT NULL,
    response_xml MEDIUMTEXT NULL,
    received_at VARCHAR(32) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uq_eet_attempts_uuid (uuid_zpravy),
    UNIQUE KEY uq_eet_attempts_no (record_id, attempt_no),
    KEY ix_eet_attempts_record (supplier_id, record_id, attempt_no),
    CONSTRAINT fk_eet_attempts_supplier FOREIGN KEY (supplier_id) REFERENCES supplier(id) ON DELETE CASCADE,
    CONSTRAINT fk_eet_attempts_record FOREIGN KEY (record_id) REFERENCES eet_records(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
